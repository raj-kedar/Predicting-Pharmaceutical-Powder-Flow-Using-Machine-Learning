<#
Builds deployment\aws\out\user-data.sh: one script to paste into
EC2 > Launch instance > Advanced details > User data.
It installs Docker, adds swap, writes /opt/flowlytix and generates a signing key.
It does NOT start the app; run deploy.sh after the Elastic IP is attached.

  .\deployment\aws\make-user-data.ps1 -ImageUri <uri printed by push-image.ps1> [-SiteMode ip|sslip]
#>
param(
  [Parameter(Mandatory = $true)][string]$ImageUri,
  [ValidateSet('ip', 'sslip')][string]$SiteMode = 'ip'
)
$ErrorActionPreference = 'Stop'
if ($ImageUri -notmatch '^(\d{12})\.dkr\.ecr\.([a-z0-9-]+)\.amazonaws\.com/[a-z0-9._/-]+:[A-Za-z0-9._-]+$') {
  throw "ImageUri must look like 123456789012.dkr.ecr.ap-south-1.amazonaws.com/flowlytix:20261122-101500"
}
$registry = $ImageUri.Split('/')[0]
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$server = Join-Path $here 'server'

function Embed([string]$name, [string]$target) {
  $body = (Get-Content -LiteralPath (Join-Path $server $name) -Raw) -replace "`r`n", "`n"
  if ($body -match '(?m)^PF_EOF$') { throw "$name contains the heredoc marker" }
  return "cat > $target <<'PF_EOF'`n$body`nPF_EOF`n"
}

$envBody = (Get-Content -LiteralPath (Join-Path $server 'env.template') -Raw) -replace "`r`n", "`n"
$envBody = $envBody.Replace('__IMAGE_URI__', $ImageUri).Replace('__SITE_MODE__', $SiteMode)

$script = @"
#!/usr/bin/env bash
# FlowLytix server setup for Ubuntu 24.04 LTS (generated by make-user-data.ps1)
set -euo pipefail
exec > >(tee -a /var/log/flowlytix-setup.log) 2>&1

export DEBIAN_FRONTEND=noninteractive
apt-get update -y
apt-get install -y docker.io docker-compose-v2 amazon-ecr-credential-helper curl openssl
systemctl enable --now docker

# 2 GB swap so small instances do not run out of memory
if [ ! -f /swapfile ]; then
  fallocate -l 2G /swapfile && chmod 600 /swapfile && mkswap /swapfile && swapon /swapfile
  echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi

# Pull from private ECR using the instance role (no keys stored on the server)
mkdir -p /root/.docker
cat > /root/.docker/config.json <<'PF_EOF'
{ "credHelpers": { "$registry": "ecr-login" } }
PF_EOF

mkdir -p /opt/flowlytix
cd /opt/flowlytix

"@
$script += Embed 'docker-compose.yml' '/opt/flowlytix/docker-compose.yml'
$script += Embed 'Caddyfile.ip' '/opt/flowlytix/Caddyfile.ip'
$script += Embed 'Caddyfile.sslip' '/opt/flowlytix/Caddyfile.sslip'
$script += Embed 'deploy.sh' '/opt/flowlytix/deploy.sh'
$script += @"
chmod 755 /opt/flowlytix/deploy.sh

# Create .env once, with a fresh signing key. Re-running never overwrites it.
if [ ! -f /opt/flowlytix/.env ]; then
  umask 077
  SECRET=`$(openssl rand -base64 48 | tr -d '\n/+=')
  cat > /opt/flowlytix/.env <<'PF_EOF'
$envBody
PF_EOF
  sed -i "s|__GENERATED__|`$SECRET|" /opt/flowlytix/.env
fi
chmod 600 /opt/flowlytix/.env

echo "FlowLytix setup finished. Attach the Elastic IP, then run: sudo /opt/flowlytix/deploy.sh"
"@

$out = Join-Path $here 'out'
New-Item -ItemType Directory -Force -Path $out | Out-Null
$path = Join-Path $out 'user-data.sh'
[System.IO.File]::WriteAllText($path, ($script -replace "`r`n", "`n"), (New-Object System.Text.UTF8Encoding $false))
Write-Host "Wrote $path"
Write-Host "Paste its contents into EC2 > Launch instance > Advanced details > User data."
